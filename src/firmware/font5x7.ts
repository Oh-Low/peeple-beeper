/** Original 5×7 column-major glyphs. Bit 0 is the top pixel. */

function pack(rows: string[]): [number, number, number, number, number] {
  const cols: [number, number, number, number, number] = [0, 0, 0, 0, 0];
  for (let y = 0; y < 7; y++) {
    const row = rows[y] ?? "     ";
    for (let x = 0; x < 5; x++) {
      if (row[x] === "#") cols[x] |= 1 << y;
    }
  }
  return cols;
}

